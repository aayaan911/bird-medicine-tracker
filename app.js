function filter(){
  var s = q.value.toLowerCase().trim();
  clrBtn.classList.toggle('show', s.length > 0);
  var shown = 0;
  P.forEach(function(p, i){
    var hay = (p.k + ' ' + p.name + ' ' + p.bl + ' ' + p.when + ' ' + p.why).toLowerCase();
    var ok = (!s || hay.indexOf(s) > -1) && (active === 'all' || p.cats.indexOf(active) > -1);
    rows[i].style.display  = ok ? '' : 'none';
    cards[i].style.display = ok ? '' : 'none';
    if (ok) shown++;
  });
  document.getElementById('rcount').textContent = shown + ' of ' + P.length + ' products';
  document.getElementById('empty').style.display = shown ? 'none' : 'block';
  vTable.style.display = (view === 'table' && shown) ? '' : 'none';
  vGal.style.display   = (view === 'gallery' && shown) ? '' : 'none';
}

function setView(v){
  view = v;
  vbtns.forEach(function(b){
    var on = b.dataset.v === v;
    b.classList.toggle('on', on);
    b.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
  try { localStorage.setItem('bmt-view', v); } catch(e){}
  if (history.replaceState) history.replaceState(null, '', '#doses-' + v);
  filter();
}

