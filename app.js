function bindCopy(root){
  Array.prototype.slice.call(root.querySelectorAll('[data-copy]')).forEach(function(btn){
    btn.addEventListener('click', function(e){
      e.preventDefault(); e.stopPropagation();
      var p = P.filter(function(x){ return x.id === btn.dataset.copy; })[0];
      if (!p) return;
      var txt = copyText(p);
      var done = function(){
        var old = btn.innerHTML;
        btn.innerHTML = DONE + 'Copied';
        btn.classList.add('ok');
        setTimeout(function(){ btn.innerHTML = old; btn.classList.remove('ok'); }, 1600);
      };
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(txt).then(done, function(){ fallback(txt, done); });
      } else { fallback(txt, done); }
    });
  });
}
function fallback(txt, done){
  var ta = document.createElement('textarea');
  ta.value = txt; ta.setAttribute('readonly','');
  ta.style.position='fixed'; ta.style.top='-1000px';
  document.body.appendChild(ta); ta.select();
  try { document.execCommand('copy'); done(); } catch(err){}
  document.body.removeChild(ta);
}


var NUTRI=[
 ['vitA','Vitamin A','IU'],['vitD3','Vitamin D3','IU'],['vitE','Vitamin E','mg'],
 ['vitC','Vitamin C','mg'],['zinc','Zinc','mg'],['selenium','Selenium','present'],
 ['iodine','Iodine','mg'],['calcium','Calcium','g'],['amino','Amino acids','count']
];
var GNAME={fertility:'Fertility products',d3:'Calcium and vitamin D3 products',multi:'Daily multivitamins',electrolyte:'Electrolyte and recovery products'};

function fmtN(v,u){
  if(!v) return '<span class="zero">none</span>';
  if(u==='present') return '<b>yes</b>';
  if(u==='count') return '<b>'+v+'</b>';
  if(v<0.01) return '<b>'+v.toFixed(5)+'</b> '+u;
  if(v<1) return '<b>'+v.toFixed(2)+'</b> '+u;
  return '<b>'+(v>=1000?Math.round(v).toLocaleString('en-IN'):v)+'</b> '+u;
}

function buildCompare(pid){
  var me=P.filter(function(x){return x.id===pid;})[0];
  if(!me) return '';
  var group = me.g ? P.filter(function(x){return x.g===me.g && x.n;}) : [me];
  if(group.length<2) group=[me];
  var score={}; group.forEach(function(g){score[g.id]=0;});
  var rows='';
  NUTRI.forEach(function(nu){
    var key=nu[0], vals=group.map(function(g){return (g.n&&g.n[key])||0;});
    var max=Math.max.apply(null,vals);
    if(max<=0) return;
    rows+='<div class="crow"><div class="ck">'+nu[1]+'</div>';
    group.forEach(function(g,i){
      var win = vals[i]>0 && vals[i]===max;
      if(win) score[g.id]+=1;
      rows+='<div class="cv'+(win?' win':'')+'">'+fmtN(vals[i],nu[2])+(win?'<span class="crown">best</span>':'')+'</div>';
    });
    rows+='</div>';
  });
  var best=null,bs=-1;
  group.forEach(function(g){ if(score[g.id]>bs){bs=score[g.id];best=g;} });
  var head='<div class="crow chead"><div class="ck">Per dose</div>';
  group.forEach(function(g){ head+='<div class="cv'+(g.id===pid?' self':'')+'">'+g.name+(g.id===pid?'<span class="crown">you</span>':'')+'</div>'; });
  head+='</div>';
  var basis='<div class="crow cbasis"><div class="ck">Basis</div>';
  group.forEach(function(g){ basis+='<div class="cv">'+((g.n&&g.n.basis)||'-')+'</div>'; });
  basis+='</div>';
  var tot='<div class="crow ctot"><div class="ck">Categories won</div>';
  group.forEach(function(g){ tot+='<div class="cv'+(g===best?' win':'')+'"><b>'+score[g.id]+'</b></div>'; });
  tot+='</div>';
  var verdict = group.length<2
    ? '<div class="cverdict">This product has no direct alternative in the list. Nothing to compare it against.</div>'
    : '<div class="cverdict"><b>'+best.name+'</b> leads on '+bs+' of the measured categories. '+esc(best.alt)+'</div>';
  return '<div class="cwrap" style="--cn:'+group.length+'">'+head+basis+rows+tot+'</div>'
    +verdict
    +'<div class="cnote">Values are what one label dose actually delivers, converted to a common basis so the numbers are comparable. Blank means the manufacturer does not declare it, which is not the same as zero. A product winning more categories is not automatically the right choice, match the product to the job.</div>';
}

